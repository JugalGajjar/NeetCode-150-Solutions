class Solution:
    def trap(self, height: list[int]) -> int:
        if not height:
            return 0

        left, right = 0, len(height) - 1
        left_max, right_max = height[left], height[right]
        total_water = 0

        while left < right:
            if left_max < right_max:
                left += 1
                left_max = max(left_max, height[left])
                total_water += left_max - height[left]
            else:
                right -= 1
                right_max = max(right_max, height[right])
                total_water += right_max - height[right]

        return total_water

# Time Complexity: O(n), where n is the length of the height list.
# We traverse the list once with two pointers.
# Space Complexity: O(1)
# We use constant extra space, as we only store a few variables for the pointers and maximum heights.